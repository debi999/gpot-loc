# RPG Maker 数据库里值得提取的字段（与引擎 rpgmaker.py 的 RPG_DB_FIELDS 对齐）
_DB_FILES = [
    'CommonEvents.json', 'Actors.json', 'Items.json', 'Weapons.json',
    'Armors.json', 'Skills.json', 'States.json', 'Enemies.json',
    'Troops.json', 'Classes.json', 'MapInfos.json', 'System.json',
]

# System.json 里是开关/变量名，不是玩家可见文本，但仍是可翻译项。
# 实测占 709 条（19%），保留但排在后面。

_MAP_RE = re.compile(r'^Map\d+\.json$')

# ---- 通用兜底的启发式 ----------------------------------------------------
# JSON 里哪些字符串像「玩家会看到的文本」：
#  · 长度 >= 2
#  · 不含控制字符
#  · 至少有一个字母
#  · 不是纯数字/纯符号/纯空白
#  · 排除颜色代码 `\c[3]`
_CTRL_RE = re.compile(r'[\x00-\x08\x0b\x0c\x0e-\x1f]')
_COLOR_CODE_RE = re.compile(r'^\\c\[?\d*\]?$')
_KEYLIKE_RE = re.compile(r'^[A-Za-z_][A-Za-z0-9_]*$')   # Actors.json#obj1-name 这类键
_NUMERIC_RE = re.compile(r'^[\d\s.,:%\-*/+()]*$')

# ---- 噪声黑名单（v3.27 实测 69,471 条全量遍历后归纳）--------------------
# 事件脚本里大量**开发者注释**与**内部命令**，不是玩家可见文本。
# 实测样本：
#   '** SET CLAW POSITION **'     ← 开发者注释
#   'AnimatedPicture 7 Speed 8'   ← 内部命令参数
#   'HC_Zombies2B'                ← 图集文件名（无空格，靠下划线判据拦）
#   'Thunder5'                    ← 音效文件名
#   '3MerOlivSex1a[4x4]'          ← 贴图图集名
_NOTE_WRAP_RE = re.compile(r'^[<>*_#\s]')
_SNAKE_UPPER_RE = re.compile(r'^[A-Za-z]*[A-Z][A-Za-z]*(_[A-Za-z0-9]+)+$')  # HC_Zombies2B
_CAMEL_NUM_RE = re.compile(r'^[A-Za-z]+\d+$')           # Thunder5
_ALL_CAPS_RE = re.compile(r'^[A-Z0-9 _]+$')             # SET CLAW POSITION
_VARNAME_RE = re.compile(r'^[A-Za-z_][A-Za-z0-9_]*$')     # 变量名 / 图集名
# camelCase 标识符：Spriteset2 / myVar / someField
_CAMEL_RE = re.compile(r'^[a-z]+[A-Z]')
# RPG Maker 控制码：`\!` `\.` `\p` `\l` `\v` `\n` `\^` `\$` `\>` `\<` `\|`
_CTRLCODE_RE = re.compile(r'\\[.!pLv n^$><|]')
# 字体标记 `<Coffee Junkie>` 是**说话人名字**，要保留；但 `\n<\n[2]>` 是换行+色码，是噪声
_LEADING_NL_CODE_RE = re.compile(r'^(\\n)+\s*<\s*\\n\s*\[\d+\]\s*')
# ---- JS 代码 / 脚本调用（v3.27 第二轮实测追加）---------------------------
#   'Galv.PROJ.dir(7,4,10,7,\'BulletMotorLZ\',0,\'c(196)'  ← 子弹脚本
#   '$gameSelfSwitches.setValue([m, e, \'D\'], false);'   ← JS 赋值
#   'Galv.BattleM.animate(...)'                          ← 战斗插件
# 判据：含JS 特征 —— `$` 变量 / `Xxx.Yyy(` 调用 / `function` / `;` 收尾 / `===`
_JS_CALL_RE = re.compile(r'\b[A-Za-z_][A-Za-z0-9_]*\.[A-Za-z_][A-Za-z0-9_]*\s*\(')
_JS_VAR_RE = re.compile(r'^\$[A-Za-z_]')
_JS_KEYWORD_RE = re.compile(
    r'\b(function|var|let|const|return|if|else|for|while|switch|case|break|'
    r'continue|new|typeof|instanceof|this|null|undefined|true|false)\b')
# ---- 带数字的图集/角色贴图名（v3.27 第三轮实测追加，残留 3,907 条）--------
#   '1MC1' '7HP_10' '1Aunt1' '1Jenny' '3MeredithShop1x[4x4]'
#   —— 事件里 image.char / image.name 字段都是图集名，不是文本。
#   判据：**无空格 + 含数字 + 不含逗号句号** —— 玩家文本几乎总是有空格和标点。
_SPRITE_NUM_RE = re.compile(r'^(?=.*\d)[A-Za-z0-9_\[\]x]+$')
# `[4x4]` 这种图集尺寸标记
_ATLAS_DIM_RE = re.compile(r'\[\d+x\d+\]$')
# 纯小写 + 可选结尾句点：**音效文件名**（实测 `city.` / `Bells` / `Door1` 等）。
# ⚠️ 只拦**带结尾句点**的（`city.` / `door.`）——音效文件名几乎都带句点，
#    而合法英文文本很少以「小写单词+句点」结尾（那通常是省略号残片，
#    由is_truncated_fragment 那一层管）。
#    裸小写单词（`ok` / `no` / `yes` / `Bells` / `Door1`）**一律放行**，
#    它们可能是道具名/事件名，误伤代价比漏掉几个音效高。
_SFX_DOT_RE = re.compile(r'^[a-z]{2,20}\.$')


def find_data_dir(game_dir):
    """定位 RPG Maker 的数据目录。返回路径或 None。

    标准布局：
      <root>/www/data        (MV/MZ)
      <root>/data            (直接包一层的情况)
    必须含 MapInfos.json 才认（避免误认普通 data 目录）。
    """
    if not game_dir or not os.path.isdir(game_dir):
        return None
    cands = [
        os.path.join(game_dir, 'www', 'data'),
        os.path.join(game_dir, 'data'),
    ]
    for c in cands:
        if os.path.isfile(os.path.join(c, 'MapInfos.json')):
            return c
    # 兜底：向下找两层
    for root, dirs, files in os.walk(game_dir):
        dirs[:] = [d for d in dirs if not d.startswith('.')]
        if 'MapInfos.json' in files:
            return root
        if root[len(game_dir):].count(os.sep) >= 3:
            dirs[:] = []
    return None


def detect(game_dir):
    """是否是 RPG Maker MV/MZ。返回 (是与否, 数据目录 或 None, 引擎名)。"""
    d = find_data_dir(game_dir)
    if not d:
        return False, None, None
    # 区分 MV / MZ：MZ 有 class 目录和 js/rmmz_*.js；MV 有 js/rpg_*.js
    js = os.path.join(os.path.dirname(d), 'js')
    mz = False
    if os.path.isdir(js):
        try:
            names = os.listdir(js)
        except Exception:
            names = []
        mz = any(n.startswith('rmmz_') for n in names)
    # 字体目录也可参考：MV 是 gamefont， MZ 是 mzfont
    fonts = os.path.join(os.path.dirname(d), 'fonts')
    if os.path.isdir(fonts):
        try:
            fn = os.listdir(fonts)
        except Exception:
            fn = []
        if any('mzfont' in n.lower() for n in fn):
            mz = True
    return True, d, ('RPGMakerMZ' if mz else 'RPGMakerMV')


