_JSON_EVENT_RE = re.compile(
    r'"(?:code|parameters|list|name|description|text|message|choice)"\s*:')
_PUNCT_TAIL_RE = re.compile(r'[.!?"\')\]]\s*$')


def _generic_walk(obj, path, out):
    """按 JSON 里常见的文本承载字段名提取（事件指令/数据库对象）。"""
    if isinstance(obj, str):
        t = obj.strip()
        if _looks_like_text(t) and not _is_dev_noise(t):
            out.append((path, t))
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            _generic_walk(v, '%s-%d' % (path, i), out)
    elif isinstance(obj, dict):
        for k, v in obj.items():
            # 命中已知文本字段名 → 只取字符串，不下钻（避免把图片名也捞进来）
            if isinstance(v, str) and k in (
                    'text', 'message', 'name', 'description', 'choice',
                    'speaker', 'title'):
                t = v.strip()
                if _looks_like_text(t) and not _is_dev_noise(t):
                    out.append(('%s.%s' % (path, k), t))
            else:
                _generic_walk(v, '%s.%s' % (path, k), out)


def extract_generic(game_dir):
    """兜底提取：遍历所有 .json，挑出「像自然语句」的字符串。

    比结构化提取宽松—— 宁可多收噪声，也不要让用户看到「扫描到 0 条」。
    额外过滤：只保留**含空格**且**像句子**的字符串（降低 JSON 键名/枚举噪声）。
    """
    ok, data_dir, _ = detect(game_dir)
    if not ok:
        return [], {'data_dir': None, 'stats': {}}
    rows = []
    stats = {}
    try:
        names = sorted(os.listdir(data_dir))
    except Exception:
        return [], {'data_dir': data_dir, 'stats': {}}
    for name in names:
        if not name.endswith('.json'):
            continue
        p = os.path.join(data_dir, name)
        try:
            if os.path.getsize(p) > 60 * 1024 * 1024:
                stats[name] = -2# 过大，跳过
                continue
            with open(p, 'rb') as fh:
                obj = json.loads(fh.read().decode('utf-8'))
        except Exception:
            stats[name] = -1
            continue
        got = []
        _generic_walk(obj, name[:-5], got)
        n = 0
        seen = set()
        for path, s in got:
            if s in seen:
                continue
            # 只要「像句子」的：含空格 + 至少 3 词 + 长度 >= 8
            # 放过 UI 短标签（Claw / Sword）—— 那些由结构化提取负责
            if len(s) >= 8 and ' ' in s and len(s.split()) >= 3:
                seen.add(s)
                rows.append(('%s#%s' % (name, path), s))
                n += 1
        stats[name] = n
    return rows, {'data_dir': data_dir, 'stats': stats}


