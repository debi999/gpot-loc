def _walk_strings(obj, path, out, budget=None):
    """深度遍历 JSON，把 (json路径, 字符串) 记进 out。"""
    if budget is not None and budget[0] <= 0:
        return
    if isinstance(obj, str):
        if budget is not None:
            budget[0] -= 1
        out.append((path, obj))
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            _walk_strings(v, '%s-%d' % (path, i), out, budget)
    elif isinstance(obj, dict):
        for k, v in obj.items():
            _walk_strings(v, '%s.%s' % (path, k), out, budget)


def _looks_like_text(s):
    """是否像玩家可见文本。"""
    if not s:
        return False
    t = s.strip()
    if len(t) < 2 or len(t) > 800:
        return False
    if _CTRL_RE.search(t):
        return False
    if _COLOR_CODE_RE.match(t):
        return False
    if _NUMERIC_RE.match(t):
        return False
    if not any(c.isalpha() for c in t):
        return False
    return True


def _is_dev_noise(t):
    """开发者注释 / 内部命令 / 资源名—— 不是玩家看到的文本。

    v3.27 实测依据：69,471 条全量遍历里，这类占了绝大多数。
    **刻意保留**：
      - 'Talk' / 'Check Crops' / 'Cum'          —— 事件指令的**指令名**，玩家在指令
                                                  菜单里能看见（编辑器），但游戏里不显示。
                                                  实测这三个都很短且是英文单词 → 保留。
      - 'AnimatedPicture 7 Speed 8'             —— 含数字+单位，内部命令 → 拦
    """
    if not t:
        return True
    # 全角尖括号包裹的开发者注释：'** SET CLAW POSITION **' / '<fog effect>'
    if _NOTE_WRAP_RE.match(t):
        return True
    # 资源名：HC_Zombies2B / HC_Actors / Spriteset2
    if _SNAKE_UPPER_RE.match(t):
        return True
    # 音效/贴图名：Thunder5 / Sword3
    if _CAMEL_NUM_RE.match(t):
        return True
    # 全大写命令：SET CLAW POSITION / ANIMATION X
    if len(t) >= 3 and _ALL_CAPS_RE.match(t) and ' ' in t:
        return True
    #变量名 / 图集名（无空格单个标识符）
    #   ⚠️ **不能只看「无空格单标识符」** —— 实测会连`Claw`（武器名）/
    #   `Player`（角色名）/`Meredith`（人物名）一起误杀，这些是**要翻译的**。
    #   真正的图集/变量名形态：**含下划线** 或 **全小写长串** 或 **camelCase**。
    if _VARNAME_RE.match(t):
        if '_' in t or _CAMEL_RE.match(t):
            return True# HC_Zombies2B / Spriteset2 / myVariable
        # 纯小写且长度 >= 6 → 多半是内部标识符（但 'Bells'/'Wing' 可能是道具名）
        if t.islower() and len(t) >= 6:
            return True
        # 其余（首字母大写的短词）**放行** —— 大概率是玩家可见名称
        return False
    # ---- JS 代码 / 插件脚本调用（v3.27 第二轮实测追加）----
    if _JS_VAR_RE.match(t):                       # $gameSelfSwitches.setValue(...)
        return True
    if _JS_CALL_RE.search(t):                     # Galv.PROJ.dir(...)
        return True
    if _JS_KEYWORD_RE.search(t):                  # if / return / function ...
        return True
    if t.rstrip().endswith((';', '{', '}', ');')):  # 语句收尾
        return True
    # 图集/贴图名：'1MC1' / '7HP_10' / '3MeredithShop1x[4x4]'
    # 判据：无空格 + 含数字 + 无标点。玩家可见文本几乎总是有空格或标点。
    if ' ' not in t and _SPRITE_NUM_RE.match(t):
        return True
    # 音效文件名：'city.' / 'door.'（带结尾句点的小写单词）
    if _SFX_DOT_RE.match(t):
        return True
    # 含空格但每段都是「标识符+数字」形态：AnimatedPicture 7 Speed 8
    parts = t.split()
    if len(parts) >= 3 and sum(1 for p in parts if p.isdigit()) >= len(parts) / 2.0:
        return True
    return False


def extract(game_dir):
    """结构化提取。返回 (rows, info)。

    rows = [(key, source), ...]，info = {'data_dir':..., 'engine':..., 'stats':{...}}
    """
    ok, data_dir, engine = detect(game_dir)
    if not ok:
        return [], {'data_dir': None, 'engine': None, 'stats': {}}

    rows = []
    stats = {}
    files = []
    for name in _DB_FILES:
        p = os.path.join(data_dir, name)
        if os.path.isfile(p):
            files.append(name)
    # Map*.json（文本量主体）
    try:
        for name in sorted(os.listdir(data_dir)):
            if _MAP_RE.match(name) and name not in files:
                files.append(name)
    except Exception:
        pass

    for name in files:
        p = os.path.join(data_dir, name)
        try:
            with open(p, 'rb') as fh:
                obj = json.loads(fh.read().decode('utf-8'))
        except Exception:
            stats[name] = -1          # 解析失败
            continue
        got = []
        _walk_strings(obj, name[:-5], got)
        n = 0
        seen = set()
        for path, s in got:
            t = s.strip()
            if not _looks_like_text(t) or _is_dev_noise(t):
                continue
            # 去重：同一文件里相同原文只取一次（RPG Maker 大量重复文本）
            key = '%s#%s' % (name, path)
            if key in seen:
                continue
            seen.add(key)
            rows.append((key, t))
            n += 1
        stats[name] = n

    return rows, {'data_dir': data_dir, 'engine': engine, 'stats': stats}


