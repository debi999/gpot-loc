def _lookup(trs, s):
    """查译文字典。命中返回新串，未命中返回 None。

    兼容提取侧的 `strip()`：json 里的值可能带前后空白，
    替换时**保留**原来的空白，只换中间的文本。
    """
    if not isinstance(s, str) or not s:
        return None
    v = trs.get(s)
    if v:
        return v
    t = s.strip()
    if t and t in trs:
        return s.replace(t, trs[t])
    return None


def _tr_str(trs, container, key, stat, miss):
    """原地替换 dict 里的一个字符串字段。命中则 stat['applied'] += 1。"""
    old = container.get(key)
    if not isinstance(old, str) or not old:
        return False
    new = _lookup(trs, old)
    if new is None or new == old:
        if old.strip() and old.strip() not in trs:
            miss.add(old.strip())
        return False
    container[key] = new
    stat['applied'] += 1
    return True


def _tr_event_list(trs, lst, stat, miss):
    """替换事件指令序列里的文本。就地修改。"""
    if not isinstance(lst, list):
        return
    for cmd in lst:
        if not isinstance(cmd, dict):
            continue
        code = cmd.get('code')
        params = cmd.get('parameters')
        if code == _EVENT_LIST_CODE and isinstance(params, list) and params:
            choices = params[0]
            if isinstance(choices, list):
                for i, c in enumerate(choices):
                    if isinstance(c, str):
                        n = _lookup(trs, c)
                        if n is not None and n != c:
                            choices[i] = n
                            stat['applied'] += 1
                        elif c.strip() and c.strip() not in trs:
                            miss.add(c.strip())
            continue
        idxs = _EVENT_TEXT_CODES.get(code)
        if not idxs or not isinstance(params, list):
            continue
        for i in idxs:
            if i < len(params) and isinstance(params[i], str):
                n = _lookup(trs, params[i])
                if n is not None and n != params[i]:
                    params[i] = n
                    stat['applied'] += 1
                elif params[i].strip() and params[i].strip() not in trs:
                    miss.add(params[i].strip())


def _apply_db_file(trs, name, obj, stat, miss, include_note):
    """数据库类 json（数组，首元素常为 null）。就地修改。"""
    base = name[:-5]
    fields = _DB_TEXT_FIELDS.get(base)
    if fields is None:
        return False
    if include_note:
        fields = tuple(fields) + ('note',)
    changed = False
    if not isinstance(obj, list):
        return False
    for item in obj:
        if not isinstance(item, dict):
            continue
        for f in fields:
            if f in item:
                if _tr_str(trs, item, f, stat, miss):
                    changed = True
    return changed


def _apply_map_file(trs, obj, stat, miss):
    """Map*.json：只翻 events[].pages[].list 里的文本行。"""
    changed = False
    events = obj.get('events') if isinstance(obj, dict) else None
    if not isinstance(events, list):
        return False
    for ev in events:
        if not isinstance(ev, dict):
            continue
        for page in ev.get('pages') or []:
            if not isinstance(page, dict):
                continue
            _tr_event_list(trs, page.get('list'), stat, miss)
            changed = True      # 是否真的改了由 applied 计数体现
    return changed


def _apply_system_file(trs, obj, stat, miss):
    """System.json：术语/菜单/类型名。switches/variables 一律跳过。"""
    if not isinstance(obj, dict):
        return False
    changed = False
    for k in _SYSTEM_TEXT_KEYS:
        if k in obj:
            if _tr_str(trs, obj, k, stat, miss):
                changed = True
    for k in _SYSTEM_LIST_KEYS:
        arr = obj.get(k)
        if isinstance(arr, list):
            for i, v in enumerate(arr):
                if isinstance(v, str):
                    n = _lookup(trs, v)
                    if n is not None and n != v:
                        arr[i] = n
                        stat['applied'] += 1
                        changed = True
                    elif v.strip() and v.strip() not in trs:
                        miss.add(v.strip())
    terms = obj.get('terms')
    if isinstance(terms, dict):
        for _tk, tv in terms.items():
            if isinstance(tv, list):
                for i, v in enumerate(tv):
                    if isinstance(v, str):
                        n = _lookup(trs, v)
                        if n is not None and n != v:
                            tv[i] = n
                            stat['applied'] += 1
                            changed = True
                        elif v.strip() and v.strip() not in trs:
                            miss.add(v.strip())
            elif isinstance(tv, dict):
                for k2, v2 in tv.items():
                    if isinstance(v2, str):
                        n = _lookup(trs, v2)
                        if n is not None and n != v2:
                            tv[k2] = n
                            stat['applied'] += 1
                            changed = True
                        elif v2.strip() and v2.strip() not in trs:
                            miss.add(v2.strip())
    return changed


def game_root(data_dir):
    """由 data 目录推回游戏根目录。

    MV 是 `<root>/www/data`（上两级），MZ 是 `<root>/data`（上一级）——
    ⚠️ 一律上两级会把 MZ 的备份写到游戏目录**外面**去，必须按布局判断。
    """
    parent = os.path.dirname(os.path.abspath(data_dir))
    if os.path.basename(parent).lower() == 'www':
        return os.path.dirname(parent)
    return parent


def backup(data_dir, backup_root):
    """全量备份 data 目录到 `<backup_root>/data-<时间戳>/`。返回备份路径。

    ⚠️ 回写**前必做**。这是老板授权 apply 的前提条件。
    """
    if not os.path.isdir(data_dir):
        raise ValueError('data 目录不存在: %s' % data_dir)
    os.makedirs(backup_root, exist_ok=True)
    stamp = time.strftime('%Y%m%d-%H%M%S')
    dst = os.path.join(backup_root, 'data-%s' % stamp)
    n = 0
    while os.path.exists(dst):
        n += 1
        dst = os.path.join(backup_root, 'data-%s-%d' % (stamp, n))
    shutil.copytree(data_dir, dst)
    return dst


def list_backups(backup_root):
    """列出可用备份点，新的在前。"""
    if not os.path.isdir(backup_root):
        return []
    out = []
    for name in os.listdir(backup_root):
        p = os.path.join(backup_root, name)
        if os.path.isdir(p) and name.startswith('data-'):
            out.append((name, p))
    out.sort(reverse=True)
    return out


def restore(backup_dir, data_dir):
    """把备份还原回 data 目录（先清空再整体拷回）。返回还原文件数。"""
    if not os.path.isdir(backup_dir):
        raise ValueError('备份目录不存在: %s' % backup_dir)
    if not os.path.isdir(data_dir):
        raise ValueError('data 目录不存在: %s' % data_dir)
    # 只覆盖备份里存在的文件，保留 data 里新增的文件
    n = 0
    for root, _dirs, files in os.walk(backup_dir):
        rel = os.path.relpath(root, backup_dir)
        dst_dir = data_dir if rel == '.' else os.path.join(data_dir, rel)
        os.makedirs(dst_dir, exist_ok=True)
        for f in files:
            shutil.copy2(os.path.join(root, f), os.path.join(dst_dir, f))
            n += 1
    return n


def apply(game_dir, translations, backup_root=None, include_note=False,
          make_backup=True):
    """把 `{原文: 译文}` 回写进 www/data/*.json。

    返回 dict：
      ok / engine / data_dir / backup / stats{files,changed_files,applied,miss}
      / miss_sample（前 20 条未命中原文）

    ⚠️ 会修改游戏本体数据 —— 调用前必须已取得用户许可，且 `make_backup=True`
       时会先全量备份。
    """
    ok, data_dir, engine = detect(game_dir)
    if not ok:
        return {'ok': False, 'reason': '不是 RPG Maker MV/MZ 工程'}
    trs = {}
    for k, v in (translations or {}).items():
        if isinstance(k, str) and k and isinstance(v, str) and v:
            trs[k] = v
    if not trs:
        return {'ok': False, 'reason': '译文为空'}

    bk = None
    if make_backup:
        if backup_root is None:
            backup_root = os.path.join(game_root(data_dir), '_原文备份')
        bk = backup(data_dir, backup_root)

    stat = {'files': 0, 'changed_files': 0, 'applied': 0}
    miss = set()
    try:
        names = sorted(os.listdir(data_dir))
    except Exception:
        return {'ok': False, 'reason': '无法列出 data 目录', 'backup': bk}

    for name in names:
        if not name.lower().endswith('.json'):
            continue
        p = os.path.join(data_dir, name)
        try:
            with open(p, 'rb') as fh:
                raw = fh.read()
            obj = json.loads(raw.decode('utf-8-sig'))
        except Exception:
            continue
        stat['files'] += 1
        before = stat['applied']
        changed = False
        if name == 'System.json':
            changed = _apply_system_file(trs, obj, stat, miss)
        elif name == 'CommonEvents.json':
            if isinstance(obj, list):
                for item in obj:
                    if isinstance(item, dict):
                        _tr_event_list(trs, item.get('list'), stat, miss)
                changed = True
        elif name == 'Troops.json':
            if isinstance(obj, list):
                for item in obj:
                    if not isinstance(item, dict):
                        continue
                    for page in item.get('pages') or []:
                        if isinstance(page, dict):
                            _tr_event_list(trs, page.get('list'), stat, miss)
                changed = True
        elif name == 'MapInfos.json':
            if isinstance(obj, list):
                for item in obj:
                    if isinstance(item, dict) and 'name' in item:
                        _tr_str(trs, item, 'name', stat, miss)
                changed = True
        elif _MAP_RE.match(name):
            changed = _apply_map_file(trs, obj, stat, miss)
        else:
            changed = _apply_db_file(trs, name, obj, stat, miss, include_note)

        if changed and stat['applied'] > before:
            stat['changed_files'] += 1
            tmp = p + '.tmp_apply'
            with open(tmp, 'w', encoding='utf-8', newline='') as fh:
                json.dump(obj, fh, ensure_ascii=False, separators=(',', ':'))
            os.replace(tmp, p)
        elif changed:
            # 结构变了但没命中任何译文 → 不落盘，避免无意义改动
            pass

    return {
        'ok': True,
        'engine': engine,
        'data_dir': data_dir,
        'backup': bk,
        'stats': dict(stat, miss=len(miss)),
        'miss_sample': sorted(miss)[:20],
    }