def test_p0_1_translate_job_never_autosaves(tmp_path, monkeypatch):
    """翻译任务跑完 → 内存里有译文，磁盘上**必须没有**文件。"""
    gd = tmp_path / "game"
    (gd / "BepInEx" / "Translation" / "zh" / "Text").mkdir(parents=True)
    s = store_mod.Store()
    s.game = {"path": str(gd), "name": "t", "existing": 0}
    s.tstore.entries = [
        {"original": "Hello", "translation": "", "status": "untranslated"}]
    s.tstore.path = None            # 模拟「翻译路径上从未赋值」

    class FakeTr:
        def __init__(self, cfg):
            pass

        @staticmethod
        def translate_batch_fast(texts):
            return ["你好" for _ in texts]

    monkeypatch.setattr(translate.kernel, "Translator", FakeTr)
    jid = translate.start_translate(s, False)
    for _ in range(100):
        j = translate.get_job(s, jid)
        if j and not j["running"]:
            break
        time.sleep(0.05)
    assert j["progress"] == 100.0

    # 关键断言：内存有、磁盘没有 —— 写盘只由第 5 步「保存并应用」触发
    assert s.tstore.entries[0]["translation"] == "你好"
    assert s.tstore.dirty is True
    expect = (gd / "BepInEx" / "Translation" / "zh" / "Text"
              / "_AutoGeneratedTranslations.txt")
    assert not expect.is_file(), "翻译任务不得自动写盘（老板要求手动控制）"
    assert "saved" not in s.translate and "save_error" not in s.translate, \
        "自动落盘的落点/错误字段应随回退一并移除"


