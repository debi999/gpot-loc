# P1-1  取消旧任务不得踩掉新任务的 running 标志
# ===========================================================================
def test_p1_1_cancel_does_not_stomp_new_job(tmp_path, monkeypatch):
    """取消 job1 → 立刻开 job2 → job1 收尾后 running 仍为 True（原 bug：被清成 False）。

    时序用 Event 闸门卡死，不靠 sleep 猜：job1 卡在 run_chunk 里，
    期间取消并起 job2，再放行 job1，看它收尾会不会误清 job2 的标志。
    """
    gd = tmp_path / "game"
    (gd / "BepInEx" / "Translation" / "zh" / "Text").mkdir(parents=True)
    s = store_mod.Store()
    s.game = {"path": str(gd), "name": "t", "existing": 0}
    s.tstore.entries = [
        {"original": "T%d" % i, "translation": "", "status": "untranslated"}
        for i in range(80)]

    gates = {"job1": threading.Event(), "job2": threading.Event()}

    class GatedTr:
        def __init__(self, cfg):
            # job1 的 worker 先起来 → 拿 job1 的闸门；之后 job2 拿自己的
            self.gate = gates["job1"] if not gates["job1"].is_set() \
                and s.translate.get("_taken") is None else gates["job2"]

        def translate_batch_fast(self, texts):
            self.gate.wait(10)
            return ["译" + t for t in texts]

    # 用计数区分先后：第一个创建的 Translator 归 job1
    made = []

    class SeqTr:
        def __init__(self, cfg):
            made.append(self)
            self.gate = gates["job1"] if len(made) == 1 else gates["job2"]

        def translate_batch_fast(self, texts):
            self.gate.wait(10)
            return ["译" + t for t in texts]

    monkeypatch.setattr(translate.kernel, "Translator", SeqTr)
    jid1 = translate.start_translate(s, False)
    time.sleep(0.3)
    assert len(made) == 1 and made[0].gate is gates["job1"]
    assert translate.cancel_job(s, jid1) is True

    jid2 = translate.start_translate(s, False)
    assert jid2, "取消后应允许开新任务"
    assert s.translate["running"] is True

    gates["job1"].set()          # 放行 job1 → 它走到收尾
    for _ in range(100):
        if not translate.get_job(s, jid1)["running"]:
            break
        time.sleep(0.05)
    assert s.translate["running"] is True, \
        "job1 收尾把 job2 的 running 标志踩掉了"
    assert translate.start_translate(s, False) is None, \
        "job2 还在跑，第三个任务不应被放行"

    gates["job2"].set()         # 收尾，别留悬挂线程
    for _ in range(100):
        if not translate.get_job(s, jid2)["running"]:
            break
        time.sleep(0.05)


