# P0-1  落盘由用户手动控制 —— 翻译任务**不得**自动写盘
#
# ⚠️ 这是**明确的产品决定**（老板 2026-10-11）：审查报告建议「翻译完自动
#    落盘」，被否决。译文写盘**只**发生在第 5 步「保存并应用」(sink.apply)。
#    理由：自动写盘会在用户还没校对完时就改写词典文件，.bak 只留三代，
#    覆写不可控。代价要如实提示（tstore_dirty），但不代用户做决定。
